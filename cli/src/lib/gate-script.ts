import { parse } from 'yaml';

/**
 * The project's gate script (design §6): one POSIX shell file that runs the required commands of
 * `gates.yaml` in order and keeps their output, so a hook tool needs one line and the audit can tell
 * whether a commit passed. reins writes it; nothing in it calls reins or the network.
 */
export const GATE_SCRIPT = '.agents/harness/run-gates.sh';

/** Where the script keeps its logs: one file per tree hash of what was checked. */
export const GATE_LOGS = '.loctx/reports/gates';

/** The one line a hook tool runs for a stage (`pre-commit`, `pre-push`). */
export const hookLine = (stage: string): string => `sh ${GATE_SCRIPT} ${stage}`;

/** The required (not optional) gate commands of a `gates.yaml` text, in its order. */
export function requiredGates(text: string | undefined): string[] {
  if (text === undefined) return [];
  const g = parse(text) as {
    gates?: Record<string, { cmd?: string; optional?: boolean } | null>;
    order?: string[];
  } | null;
  const gates = g?.gates ?? {};
  return (g?.order ?? Object.keys(gates))
    .map((n) => gates[n])
    .filter((x): x is { cmd: string } => !!x?.cmd && !x.optional)
    .map((x) => x.cmd);
}

const quote = (s: string): string => `'${s.replaceAll("'", `'\\''`)}'`;

/** The script for these commands. The commands are written in, so the hook line never changes with them. */
export function renderGateScript(cmds: string[]): string {
  return `#!/bin/sh
# generated by reins from .agents/harness/gates.yaml — do not edit; \`reins config gates\` or \`reins update\` rewrites it
#
# Runs the project's required checks in order and keeps their output in ${GATE_LOGS}/<tree>.log,
# where <tree> is the tree hash of what is checked: \`git rev-parse <commit>^{tree}\` names a commit's log.
# Usage: sh ${GATE_SCRIPT} <stage>   (pre-commit, pre-push, audit, or any name of your own)
stage="\${1:-manual}"
root=$(git rev-parse --show-toplevel 2>/dev/null) || {
  echo "run-gates: not inside a git work tree" >&2
  exit 2
}
cd "$root" || exit 2
# pre-commit checks what is about to be committed (the index git prepared for this commit); every other
# stage checks HEAD. The checks run in the work tree, so a work tree that differs from that tree is "dirty"
# and the run is no evidence for it.
if [ "$stage" = pre-commit ]; then
  tree=$(git write-tree 2>/dev/null)
  if git diff --quiet 2>/dev/null; then worktree=clean; else worktree=dirty; fi
else
  tree=$(git rev-parse --verify --quiet 'HEAD^{tree}')
  if git diff --quiet HEAD 2>/dev/null; then worktree=clean; else worktree=dirty; fi
fi
[ -n "$tree" ] || {
  echo "run-gates: cannot tell which tree is being checked" >&2
  exit 2
}
dir=${GATE_LOGS}
mkdir -p "$dir" || exit 2
log="$dir/$tree.log"
status="$dir/.status.$$"
printf '== %s stage: %s worktree: %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$stage" "$worktree" >>"$log"
code=0
run() {
  [ "$code" -eq 0 ] || return 0
  printf '$ %s\\n' "$1" | tee -a "$log"
  {
    sh -c "$1" 2>&1
    echo $? >"$status"
  } | tee -a "$log"
  code=$(cat "$status" 2>/dev/null || echo 1)
  rm -f "$status"
}
${cmds.map((c) => `run ${quote(c)}`).join('\n')}
printf 'exit: %s\\n' "$code" >>"$log"
exit "$code"
`;
}
