import { createHash } from 'node:crypto';
import { parse, stringify } from 'yaml';
import type { Write } from './fsx.js';
import type { RedLine } from './harness.js';
import { workTreeReader, type Reader } from './reader.js';
import { FIXED_ROLES } from './bindings.js';
import { vendorOf } from './detect.js';
import { splitFrontmatter } from './skills.js';

/**
 * Vendor files generated from `.agents/harness/` (design §6). Round one generates Claude Code only:
 * `.claude/agents/reins-<role>.md` for roles bound to Claude, and `.claude/settings.json` deny rules.
 */
export const MANIFEST = '.agents/harness/generated.yaml';

export const sha = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 16);

interface Binding {
  vendor: string;
  model: string;
  enabled?: boolean;
}

interface RoleDoc {
  role: string;
  summary: string;
  may: string[];
  mustNot: string[];
  capabilities: { write?: boolean; shell?: boolean };
  fallback?: string;
  body: string;
}

function readRole(text: string): RoleDoc {
  const { data, body } = splitFrontmatter(text);
  const d = data ?? {};
  return {
    role: String(d['role']),
    summary: String(d['summary'] ?? ''),
    may: (d['may'] as string[] | undefined) ?? [],
    mustNot: (d['must_not'] as string[] | undefined) ?? [],
    capabilities: (d['capabilities'] as RoleDoc['capabilities'] | undefined) ?? {},
    fallback: typeof d['fallback_binding'] === 'string' ? d['fallback_binding'] : undefined,
    body: body.trim(),
  };
}

/** Capabilities → Claude Code tool names to withhold. Path-level limits are not expressible here; T2 (C10) is the backstop. */
function disallowed(c: RoleDoc['capabilities']): string[] {
  const out: string[] = [];
  if (c.write === false) out.push('Edit', 'Write', 'NotebookEdit');
  if (c.shell === false) out.push('Bash');
  return out;
}

export function claudeAgent(r: RoleDoc, b: Binding, version: string, fallbackFor?: string): string {
  const fm: Record<string, unknown> = {
    name: `reins-${r.role}`,
    description: `reins ${r.role} role. ${r.summary}`,
    model: b.model,
  };
  const dis = disallowed(r.capabilities);
  if (dis.length) fm['disallowedTools'] = dis.join(', ');
  return [
    '---',
    stringify(fm).trimEnd(),
    '---',
    `<!-- generated by reins ${version} from .agents/harness/roles/${r.role}.md and bindings.yaml — do not edit; run \`reins update\` -->`,
    ...(fallbackFor
      ? [`<!-- fallback for ${fallbackFor} — the team binds this role to another vendor -->`]
      : []),
    '',
    `You are the **${r.role}** role of the reins harness in this repository. ${r.summary}`,
    '',
    '## You must never',
    ...r.mustNot.map((m) => `- ${m}`),
    '- break any common red line in `.agents/harness/policy/common-red-lines.yaml` (C1–C10)',
    '',
    '## You may',
    ...r.may.map((m) => `- ${m}`),
    '',
    '## Procedure',
    '',
    r.body.replace(/^# .*\n+/, ''),
    '',
    'When a stop condition in `.agents/harness/policy/stops.yaml` applies, stop and report its id. `reins check` is the verifier.',
    '',
  ].join('\n');
}

/** C4 patterns → Claude Code deny rules. A pattern that would also hide an allowed template (`.env.*` vs `.env.example`) is narrowed. */
export function denyRules(lines: RedLine[]): string[] {
  const c4 = lines.find((r) => r.id === 'C4');
  const globs = new Set<string>();
  for (const p of c4?.patterns ?? []) {
    if (p === '.env.*')
      for (const v of [
        '.env.local',
        '.env.*.local',
        '.env.development',
        '.env.production',
        '.env.staging',
        '.env.test',
      ])
        globs.add(v);
    else globs.add(p);
  }
  const rules: string[] = [];
  for (const g of globs)
    for (const t of ['Read', 'Edit']) rules.push(`${t}(${g.startsWith('**/') ? g : `**/${g}`})`);
  // A1 force push and C5 hook bypass: the user runs these explicitly, never an agent
  rules.push(
    'Bash(git push --force *)',
    'Bash(git push -f *)',
    'Bash(git push --force-with-lease *)',
    'Bash(git commit --no-verify *)',
    'Bash(git commit -n *)',
    'Bash(git push --no-verify *)',
  );
  return rules;
}

export interface Generated {
  writes: Write[];
  skipped: string[]; // roles with no Claude model to run on (no fallback, pm not on Claude)
}

/** Everything the generator owns, computed from the installed harness. Pure. */
export function generateVendorFiles(root: string, rd: Reader = workTreeReader(root)): Generated {
  const harness = '.agents/harness';
  const version = rd.read(`${harness}/VERSION`)?.trim() ?? '?';
  const out: Generated = { writes: [], skipped: [] };
  if (rd.list(harness).length === 0) return out;
  const bindingsText = rd.read(`${harness}/bindings.yaml`);
  const bindings = bindingsText
    ? ((parse(bindingsText) as { roles?: Record<string, Binding> }).roles ?? {})
    : {};
  const rolesDir = `${harness}/roles`;
  for (const p of rd
    .list(rolesDir)
    .filter((x) => /^[^/]+\.md$/.test(x.slice(rolesDir.length + 1)))
    .toSorted()) {
    const r = readRole(rd.read(p) ?? '');
    const b = bindings[r.role];
    if (!b) continue;
    // a role the team switched off gets no agent file (fixed roles cannot be off); the local file never counts
    if (b.enabled === false && !FIXED_ROLES.includes(r.role)) continue;
    // Committed team defaults only (never the local file), so no user's override makes drift.
    // A role bound to another vendor still gets a Claude file on its fallback model, else pm's.
    let model = b.model;
    let fallbackFor: string | undefined;
    if (b.vendor !== 'claude') {
      const pm = bindings['pm'];
      const fb =
        r.fallback && vendorOf(r.fallback) === 'claude'
          ? r.fallback
          : pm && pm.vendor === 'claude'
            ? pm.model
            : undefined;
      if (!fb) {
        out.skipped.push(`${r.role} → ${b.vendor} ${b.model}`);
        continue;
      }
      model = fb;
      fallbackFor = b.vendor;
    }
    out.writes.push({
      path: `.claude/agents/reins-${r.role}.md`,
      content: claudeAgent(r, { vendor: 'claude', model }, version, fallbackFor),
      why: fallbackFor ? `role ${r.role} (fallback for ${fallbackFor})` : `role ${r.role}`,
    });
  }
  // skills: Codex, Gemini and Cursor read .agents/skills/ directly; Claude Code reads a byte-identical copy
  const skills = '.agents/skills';
  const names = [
    ...new Set(rd.list(skills).map((p) => p.slice(skills.length + 1).split('/')[0] ?? '')),
  ].toSorted();
  for (const name of names) {
    if (rd.read(`${skills}/${name}/SKILL.md`) === undefined) continue;
    for (const p of rd.list(`${skills}/${name}`).toSorted())
      out.writes.push({
        path: `.claude/skills/${p.slice(skills.length + 1)}`,
        content: rd.read(p) ?? '',
        why: `skill ${name}`,
      });
  }
  const redText = rd.read(`${harness}/policy/common-red-lines.yaml`);
  if (rd.list(`${harness}/policy`).length > 0 && redText !== undefined)
    out.writes.push({
      path: '.claude/settings.json',
      content: `${JSON.stringify({ $schema: 'https://json.schemastore.org/claude-code-settings.json', permissions: { deny: denyRules((parse(redText) as { rules: RedLine[] }).rules) } }, null, 2)}\n`,
      why: 'C4 secrets, A1 force push, C5 hook bypass',
    });
  return out;
}
