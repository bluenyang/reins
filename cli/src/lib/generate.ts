import { createHash } from 'node:crypto';
import { parse, stringify } from 'yaml';
import type { Write } from './fsx.js';
import type { RedLine } from './harness.js';
import { workTreeReader, type Reader } from './reader.js';
import { resolveRoles, type BindingsV2 } from './bindings.js';
import { agentName, claudeAgents } from './agents-md.js';
import { splitFrontmatter } from './skills.js';

/**
 * Files generated from `.agents/harness/` (design §6): `.claude/agents/rs-<group>-<role>.md` for roles
 * switched on in multi mode on a Claude model, the `.claude/skills/` copy, and `.claude/settings.json` deny
 * rules. Generated from the committed team file only, so no personal override makes drift.
 */
export const MANIFEST = '.agents/harness/generated.yaml';

export const sha = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 16);

interface RoleSpec {
  does: string;
  must_not: string[];
  tools: { write?: boolean; shell?: boolean; push?: boolean };
}

interface GroupDoc {
  group: string;
  summary: string;
  roles: Record<string, RoleSpec>;
  body: string;
}

export function readGroup(text: string): GroupDoc {
  const { data, body } = splitFrontmatter(text);
  const d = data ?? {};
  return {
    group: String(d['group']),
    summary: String(d['summary'] ?? ''),
    roles: (d['roles'] as Record<string, RoleSpec> | undefined) ?? {},
    body: body.trim(),
  };
}

/** Tool permissions → Claude Code tools to withhold. A push cannot be withheld by tool; it stays a must_not. */
function disallowed(t: RoleSpec['tools']): string[] {
  const out: string[] = [];
  if (t.write === false) out.push('Edit', 'Write', 'NotebookEdit');
  if (t.shell === false) out.push('Bash');
  return out;
}

export function claudeAgent(
  g: GroupDoc,
  role: string,
  model: string,
  version: string,
  name = agentName(g.group, role),
): string {
  const r = g.roles[role]!;
  const fm: Record<string, unknown> = {
    name,
    description: `${g.group}/${role}: ${r.does}`,
    model,
  };
  const dis = disallowed(r.tools ?? {});
  if (dis.length) fm['disallowedTools'] = dis.join(', ');
  return [
    '---',
    stringify(fm).trimEnd(),
    '---',
    `<!-- generated by reins ${version} from .agents/harness/roles/${g.group}.md and bindings.yaml — do not edit -->`,
    '',
    `You are **${g.group}/${role}** in this repository. ${r.does}`,
    '',
    'The PM gave you a task and the files and decisions you need. Mark any assumption beyond them. Return your result with its evidence (file:line, commit, raw log path) to the PM; never call another model.',
    '',
    '## You must not',
    ...r.must_not.map((m) => `- ${m}`),
    ...(r.tools?.push === false ? ['- push, open PRs, merge, release or tag'] : []),
    '- do anything in `.agents/harness/policy/common-red-lines.yaml`',
    '',
    '## How',
    '',
    g.body.replace(/^# .*\n+/, ''),
    '',
  ].join('\n');
}

/** C4 patterns → Claude Code deny rules. A pattern that would also hide an allowed template (`.env.*` vs `.env.example`) is narrowed. */
export function denyRules(lines: RedLine[]): string[] {
  const c4 = lines.find((r) => r.id === 'C4');
  const globs = new Set<string>();
  for (const p of c4?.patterns ?? []) {
    if (p === '.env.*')
      for (const v of [
        '.env.local',
        '.env.*.local',
        '.env.development',
        '.env.production',
        '.env.staging',
        '.env.test',
      ])
        globs.add(v);
    else globs.add(p);
  }
  const rules: string[] = [];
  for (const g of globs)
    for (const t of ['Read', 'Edit']) rules.push(`${t}(${g.startsWith('**/') ? g : `**/${g}`})`);
  // force push and hook bypass: the user runs these explicitly, never an agent
  rules.push(
    'Bash(git push --force *)',
    'Bash(git push -f *)',
    'Bash(git push --force-with-lease *)',
    'Bash(git commit --no-verify *)',
    'Bash(git commit -n *)',
    'Bash(git push --no-verify *)',
  );
  return rules;
}

export interface Generated {
  writes: Write[];
}

/** Everything the generator owns, computed from the installed harness. Pure. */
export function generateVendorFiles(root: string, rd: Reader = workTreeReader(root)): Generated {
  const harness = '.agents/harness';
  const version = rd.read(`${harness}/VERSION`)?.trim() ?? '?';
  const out: Generated = { writes: [] };
  if (rd.list(harness).length === 0) return out;
  const text = rd.read(`${harness}/bindings.yaml`);
  const doc = text ? (parse(text) as BindingsV2 | null) : null;
  if (doc?.schema === 'reins/bindings@2') {
    const groups = new Map<string, GroupDoc>();
    for (const r of resolveRoles(doc).filter((x) => x.on)) {
      const agents = claudeAgents(r);
      if (!agents.length) continue; // other vendors are called through the delegation table
      let g = groups.get(r.group);
      if (!g) {
        const src = rd.read(`${harness}/roles/${r.group}.md`);
        if (src === undefined) continue;
        g = readGroup(src);
        groups.set(r.group, g);
      }
      const role = r.group === 'auditor' ? 'auditor' : r.role;
      if (!g.roles[role]) continue;
      for (const a of agents)
        out.writes.push({
          path: `.claude/agents/${a.name}.md`,
          content: claudeAgent(g, role, a.model, version, a.name),
          why: `role ${r.group}/${role} on ${a.model}`,
        });
    }
  }
  // skills: other agents read .agents/skills/ directly; Claude Code reads a byte-identical copy
  const skills = '.agents/skills';
  const names = [
    ...new Set(rd.list(skills).map((p) => p.slice(skills.length + 1).split('/')[0] ?? '')),
  ].toSorted();
  for (const name of names) {
    if (rd.read(`${skills}/${name}/SKILL.md`) === undefined) continue;
    for (const p of rd.list(`${skills}/${name}`).toSorted())
      out.writes.push({
        path: `.claude/skills/${p.slice(skills.length + 1)}`,
        content: rd.read(p) ?? '',
        why: `skill ${name}`,
      });
  }
  const redText = rd.read(`${harness}/policy/common-red-lines.yaml`);
  if (redText !== undefined)
    out.writes.push({
      path: '.claude/settings.json',
      content: `${JSON.stringify({ $schema: 'https://json.schemastore.org/claude-code-settings.json', permissions: { deny: denyRules((parse(redText) as { rules: RedLine[] }).rules) } }, null, 2)}\n`,
      why: 'secrets, force push, hook bypass',
    });
  return out;
}
