import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';
import type { Write } from './fsx.js';
import { redLines } from './harness.js';
import { splitFrontmatter } from './skills.js';

/**
 * Vendor files generated from `.agents/harness/` (design §6). Round one generates Claude Code only:
 * `.claude/agents/reins-<role>.md` for roles bound to Claude, and `.claude/settings.json` deny rules.
 */
export const MANIFEST = '.agents/harness/generated.yaml';

export const sha = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 16);

interface Binding {
  vendor: string;
  model: string;
}

interface RoleDoc {
  role: string;
  summary: string;
  may: string[];
  mustNot: string[];
  capabilities: { write?: boolean; shell?: boolean };
  body: string;
}

function readRole(path: string): RoleDoc {
  const { data, body } = splitFrontmatter(readFileSync(path, 'utf8'));
  const d = data ?? {};
  return {
    role: String(d['role']),
    summary: String(d['summary'] ?? ''),
    may: (d['may'] as string[] | undefined) ?? [],
    mustNot: (d['must_not'] as string[] | undefined) ?? [],
    capabilities: (d['capabilities'] as RoleDoc['capabilities'] | undefined) ?? {},
    body: body.trim(),
  };
}

/** Capabilities → Claude Code tool names to withhold. Path-level limits are not expressible here; T2 (C10) is the backstop. */
function disallowed(c: RoleDoc['capabilities']): string[] {
  const out: string[] = [];
  if (c.write === false) out.push('Edit', 'Write', 'NotebookEdit');
  if (c.shell === false) out.push('Bash');
  return out;
}

export function claudeAgent(r: RoleDoc, b: Binding, version: string): string {
  const fm: Record<string, unknown> = {
    name: `reins-${r.role}`,
    description: `reins ${r.role} role. ${r.summary}`,
    model: b.model,
  };
  const dis = disallowed(r.capabilities);
  if (dis.length) fm['disallowedTools'] = dis.join(', ');
  return [
    '---',
    stringify(fm).trimEnd(),
    '---',
    `<!-- generated by reins ${version} from .agents/harness/roles/${r.role}.md and bindings.yaml — do not edit; run \`reins update\` -->`,
    '',
    `You are the **${r.role}** role of the reins harness in this repository. ${r.summary}`,
    '',
    '## You must never',
    ...r.mustNot.map((m) => `- ${m}`),
    '- break any common red line in `.agents/harness/policy/common-red-lines.yaml` (C1–C10)',
    '',
    '## You may',
    ...r.may.map((m) => `- ${m}`),
    '',
    '## Procedure',
    '',
    r.body.replace(/^# .*\n+/, ''),
    '',
    'When a stop condition in `.agents/harness/policy/stops.yaml` applies, stop and report its id. `reins check` is the verifier.',
    '',
  ].join('\n');
}

/** C4 patterns → Claude Code deny rules. A pattern that would also hide an allowed template (`.env.*` vs `.env.example`) is narrowed. */
export function denyRules(harness: string): string[] {
  const c4 = redLines(harness).find((r) => r.id === 'C4');
  const globs = new Set<string>();
  for (const p of c4?.patterns ?? []) {
    if (p === '.env.*')
      for (const v of [
        '.env.local',
        '.env.*.local',
        '.env.development',
        '.env.production',
        '.env.staging',
        '.env.test',
      ])
        globs.add(v);
    else globs.add(p);
  }
  const rules: string[] = [];
  for (const g of globs)
    for (const t of ['Read', 'Edit']) rules.push(`${t}(${g.startsWith('**/') ? g : `**/${g}`})`);
  // A1 force push and C5 hook bypass: the user runs these explicitly, never an agent
  rules.push(
    'Bash(git push --force *)',
    'Bash(git push -f *)',
    'Bash(git push --force-with-lease *)',
    'Bash(git commit --no-verify *)',
    'Bash(git push --no-verify *)',
  );
  return rules;
}

export interface Generated {
  writes: Write[];
  skipped: string[]; // roles not bound to a vendor generated in this round
}

/** Everything the generator owns, computed from the installed harness. Pure. */
export function generateVendorFiles(root: string): Generated {
  const harness = join(root, '.agents', 'harness');
  const bindingsPath = join(harness, 'bindings.yaml');
  const version = existsSync(join(harness, 'VERSION'))
    ? readFileSync(join(harness, 'VERSION'), 'utf8').trim()
    : '?';
  const out: Generated = { writes: [], skipped: [] };
  if (!existsSync(harness)) return out;
  const bindings = existsSync(bindingsPath)
    ? ((parse(readFileSync(bindingsPath, 'utf8')) as { roles?: Record<string, Binding> }).roles ??
      {})
    : {};
  const rolesDir = join(harness, 'roles');
  if (existsSync(rolesDir))
    for (const f of readdirSync(rolesDir)
      .filter((x) => x.endsWith('.md'))
      .toSorted()) {
      const r = readRole(join(rolesDir, f));
      const b = bindings[r.role];
      if (!b) continue;
      if (b.vendor !== 'claude') {
        out.skipped.push(`${r.role} → ${b.vendor} ${b.model}`);
        continue;
      }
      out.writes.push({
        path: `.claude/agents/reins-${r.role}.md`,
        content: claudeAgent(r, b, version),
        why: `role ${r.role}`,
      });
    }
  if (existsSync(join(harness, 'policy')))
    out.writes.push({
      path: '.claude/settings.json',
      content: `${JSON.stringify({ $schema: 'https://json.schemastore.org/claude-code-settings.json', permissions: { deny: denyRules(harness) } }, null, 2)}\n`,
      why: 'C4 secrets, A1 force push, C5 hook bypass',
    });
  return out;
}
