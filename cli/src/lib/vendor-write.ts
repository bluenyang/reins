import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parse, stringify } from 'yaml';
import { MANIFEST, generateVendorFiles, sha, type Generated } from './generate.js';
import type { Finding } from './verdict.js';

/** `.agents/harness/generated.yaml` — which vendor files reins wrote, and what they looked like. */
interface Manifest {
  schema: 'reins/generated@1';
  files: Record<string, string>;
}

export function readManifest(root: string): Manifest {
  const p = join(root, MANIFEST);
  if (!existsSync(p)) return { schema: 'reins/generated@1', files: {} };
  const m = parse(readFileSync(p, 'utf8')) as Partial<Manifest> | null;
  return { schema: 'reins/generated@1', files: m?.files ?? {} };
}

export interface GenWriteResult {
  written: string[];
  removed: string[];
  unchanged: string[];
  refused: { path: string; why: string }[];
  skipped: string[];
}

/**
 * Write generated vendor files without trampling anyone (design §6, red line C3):
 * reins overwrites only what it wrote and nobody touched since; a file it never wrote is left alone.
 */
export function writeGenerated(root: string, gen: Generated, dryRun: boolean): GenWriteResult {
  const res: GenWriteResult = {
    written: [],
    removed: [],
    unchanged: [],
    refused: [],
    skipped: gen.skipped,
  };
  const before = readManifest(root).files;
  const after: Record<string, string> = {};
  const wanted = new Set(gen.writes.map((w) => w.path));
  for (const w of gen.writes) {
    const abs = join(root, w.path);
    const next = sha(w.content);
    if (!existsSync(abs)) {
      if (!dryRun) {
        mkdirSync(dirname(abs), { recursive: true });
        writeFileSync(abs, w.content);
      }
      res.written.push(w.path);
      after[w.path] = next;
      continue;
    }
    const disk = sha(readFileSync(abs, 'utf8'));
    if (disk === next) {
      res.unchanged.push(w.path);
      after[w.path] = next;
    } else if (before[w.path] === disk) {
      if (!dryRun) writeFileSync(abs, w.content);
      res.written.push(w.path);
      after[w.path] = next;
    } else {
      res.refused.push({
        path: w.path,
        why: before[w.path]
          ? 'edited by hand since reins generated it (C3) — move the change into .agents/harness and run `reins update`'
          : 'exists and was not generated by reins — merge it by hand, or delete it and run `reins update`',
      });
      const prior = before[w.path];
      if (prior) after[w.path] = prior;
    }
  }
  // files reins wrote earlier that are no longer generated (a role re-bound to another vendor)
  for (const [path, hash] of Object.entries(before)) {
    if (wanted.has(path)) continue;
    const abs = join(root, path);
    if (!existsSync(abs)) continue;
    if (sha(readFileSync(abs, 'utf8')) === hash) {
      if (!dryRun) unlinkSync(abs);
      res.removed.push(path);
    } else {
      res.refused.push({
        path,
        why: 'no longer generated, but edited by hand — delete it yourself if it is not needed',
      });
      after[path] = hash;
    }
  }
  const changed = JSON.stringify(after) !== JSON.stringify(before);
  if (changed && !dryRun) {
    mkdirSync(dirname(join(root, MANIFEST)), { recursive: true });
    writeFileSync(
      join(root, MANIFEST),
      `# vendor files generated by reins — do not edit; \`reins update\` rewrites it\n${stringify({ schema: 'reins/generated@1', files: after })}`,
    );
  }
  return res;
}

/** Drift, match layer for generated files: on disk = what reins wrote = what it would write now. */
export function driftGenerated(root: string): Finding[] {
  if (!existsSync(join(root, MANIFEST))) return [];
  const findings: Finding[] = [];
  const recorded = readManifest(root).files;
  const now = new Map(generateVendorFiles(root).writes.map((w) => [w.path, sha(w.content)]));
  for (const [path, hash] of Object.entries(recorded)) {
    const abs = join(root, path);
    if (!existsSync(abs)) {
      findings.push({
        reason: 'F2',
        verdict: 'STOP',
        path,
        message: 'generated file is missing',
        resume: 'run `reins update`',
      });
      continue;
    }
    if (sha(readFileSync(abs, 'utf8')) !== hash)
      findings.push({
        reason: 'C3',
        verdict: 'STOP',
        path,
        message: 'generated file was edited by hand',
        resume: 'change .agents/harness instead, then `reins update`',
      });
    else if (now.has(path) && now.get(path) !== hash)
      findings.push({
        reason: 'F2',
        verdict: 'STOP',
        path,
        message: 'stale — the harness changed since it was generated',
        resume: 'run `reins update`',
      });
  }
  for (const path of now.keys())
    if (!(path in recorded) && !existsSync(join(root, path)))
      findings.push({
        reason: 'F2',
        verdict: 'STOP',
        path,
        message: 'should be generated but is not',
        resume: 'run `reins update`',
      });
  return findings;
}
