def load_bindings(root: Path) -> dict:
    merged: dict = {"agents": {}, "roles": {}}
    sources = [
        template_root() / "bindings" / "models.example.toml",
        Path.home() / ".config" / "reins" / "models.toml",
        root / ".ai" / "models.toml",
    ]
    for src in sources:
        if src.exists():
            data = tomllib.loads(read(src))
            for sect in ("agents", "roles"):
                for k, v in data.get(sect, {}).items():
                    merged[sect].setdefault(k, {}).update(v)
    return merged


def binding_for(bind: dict, stage: str, state: dict) -> tuple[str, dict]:
    role = ROLE_OF.get(stage, stage)
    if stage == "escalate" and state.get("rounds", {}).get("escalate", 0) >= 2:
        role = "escalate"
    return role, bind["roles"].get(role, {})


# --------------------------------------------------------------------------- rendering


def managed_block() -> str:
    return f"""{BEGIN} v{VERSION} — generated by reins; edit outside this block -->
## Agent loop (reins)

- Loop rules: `.harness/core/loop.md`. Roles: `.harness/core/roles/*.md`. Any agent can take any
  role — read the loop file, then the role file, and do only that role's job.
- Project facts for the loop: `.harness/project.toml` (gate commands, source paths QA must not read).
- Gates: `python3 .harness/harness.py gate all --summary` (one line per gate, failing tails,
  failure-catalog matches). Run before reporting any work as done.
- State and records (gitignored): `.ai/loop/state.json`, handoffs `.ai/handoff/`, decision
  requests `.ai/decisions/`, failure catalog `.ai/knowledge/failures.md` — search it by the error
  text before any retry.
- Procedures: `.harness/core/skills/` — `loop`, `step`, `decide`, `learn`, `verify`. Agents
  without skill support read the file of the procedure they are asked to run.
- Stops: a knowledge stop writes a decision request and waits; an intent stop (design invariant,
  stable release, deleting data or tags, force push, anything hard to undo) is always a person's.
- Push, merge, and release happen only when a person invokes them.
{END}"""


def upsert_block(text: str) -> str:
    block = managed_block()
    if BEGIN in text and END in text:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    m = re.search(r"^## Language\b", text, re.M)
    if m:
        return text[: m.start()] + block + "\n\n" + text[m.start() :]
    return text.rstrip() + "\n\n" + block + "\n"


def skill_files(core: Path) -> list[tuple[str, dict[str, str], str]]:
    out = []
    for f in sorted((core / "skills").glob("*.md")):
        meta, body = frontmatter(read(f))
        out.append((meta.get("name", f.stem), meta, body))
    return out


def render_vendor(plan: Plan, bind: dict) -> None:
    core = plan.root / ".harness" / "core"
    if plan.dry and not core.exists():
        core = template_root() / "core"
    for name, meta, body in skill_files(core):
        note = f"{GENERATED} from .harness/core/skills/{name}.md; run `harness.py render` -->\n"
        fm = [f"name: {name}", f"description: {meta.get('description', '')}"]
        if meta.get("args"):
            fm.append(f"argument-hint: '{meta['args']}'")
        if meta.get("model_invocable") == "false":
            fm.append("disable-model-invocation: true")
        _write_generated(plan, f".claude/skills/{name}/SKILL.md", "---\n" + "\n".join(fm) + "\n---\n" + note + body)
        _write_generated(plan, f".cursor/commands/{name}.md", note + f"# {name}\n\n" + body)
    for role_file in sorted((core / "roles").glob("*.md")):
        meta, _ = frontmatter(read(role_file))
        role = meta.get("role", role_file.stem)
        b = bind["roles"].get(role, {})
        if b.get("agent") != "claude":
            continue
        fm = [
            f"name: loop-{role}",
            f"description: Loop role '{role}' — {meta.get('summary', '')}",
            f"model: {b.get('model', 'inherit')}",
        ]
        body = (
            f"{GENERATED} from .harness/core/roles/{role_file.name}; run `harness.py render` -->\n"
            f"Read `.harness/core/loop.md`, then `.harness/core/roles/{role_file.name}`, and follow "
            "both. Do only this role's job, write one handoff, and stop.\n"
        )
        _write_generated(plan, f".claude/agents/loop-{role}.md", "---\n" + "\n".join(fm) + "\n---\n" + body)


def _write_generated(plan: Plan, rel: str, content: str) -> None:
    p = plan.root / rel
    if p.exists() and GENERATED not in read(p):
        plan.actions.append(("skip", f"{rel} (exists, not generated by reins)"))
        plan.notes.append(f"name collision: {rel} kept; rename yours or the core skill")
        return
    plan.write(rel, content)


# --------------------------------------------------------------------------- legacy scan


def scan_legacy(root: Path) -> list[str]:
    rows: list[str] = []
    cmds = sorted((root / ".claude" / "commands").glob("*.md"))
    if cmds:
        rows.append(
            f"| `.claude/commands/` ({len(cmds)}) | {', '.join(c.stem for c in cmds)} | "
            "Claude-only. Move to `.claude/skills/` (as croffle-play did) or keep; "
            "the loop calls them as project procedures. |"
        )
    skills = sorted(p.parent.name for p in (root / ".claude" / "skills").glob("*/SKILL.md"))
    own = [s for s in skills if GENERATED not in read(root / ".claude" / "skills" / s / "SKILL.md")]
    if own:
        rows.append(
            f"| `.claude/skills/` ({len(own)}) | {', '.join(own)} | Kept as project procedures. "
            "Shared rule files (`*-workflow`) overlap `core/loop.md` only in error handling — "
            "point their error section at the failure catalog. |"
        )
    for hook in (".husky", "lefthook.yml"):
        if (root / hook).exists():
            rows.append(
                f"| `{hook}` | git hooks | Gate source of truth stays here; `project.toml` mirrors the commands. |"
            )
    ai = root / ".ai"
    if ai.is_dir():
        present = sorted(p.name for p in ai.iterdir())
        rows.append(
            f"| `.ai/` | {', '.join(present)} | Kept. Added: "
            f"{', '.join(d for d in AI_DIRS if not (ai / d).exists()) or 'nothing'}. |"
        )
        hist = list((ai / "history").glob("*.md")) if (ai / "history").is_dir() else []
        with_dec = [h for h in hist if not read(h).startswith("decisions: none")]
        if hist:
            rows.append(
                f"| `.ai/history/` | {len(hist)} files, {len(with_dec)} with decisions | Candidates "
                "for the failure catalog — run `/learn` over the ones that record a fix. |"
            )
    agents = read(root / "AGENTS.md")
    if agents and BEGIN not in agents:
        rows.append(
            "| `AGENTS.md` | no managed block | Block inserted before `## Language` (or at the end); "
            "the rest of the file is untouched. |"
        )
    claude = read(root / "CLAUDE.md")
    if claude.strip() and "@AGENTS.md" not in claude:
        rows.append("| `CLAUDE.md` | does not import AGENTS.md | Left as is — add `@AGENTS.md`. |")
    if (root / "CLAUDE.md").exists() and not claude.strip():
        rows.append("| `CLAUDE.md` | empty | Left as is — it should contain `@AGENTS.md`. |")
    return rows


