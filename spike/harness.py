def cmd_install(a: argparse.Namespace, migrate: bool = False) -> int:
    root = Path(a.project).resolve()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2
    if HERE == root / ".harness":
        print("run install/update from the template repository, not from an installed copy", file=sys.stderr)
        return 2
    plan = Plan(root, a.dry_run)
    prof = detect(root, a.stack)
    legacy = scan_legacy(root) if migrate else []
    fresh_profile = not (root / ".harness" / "project.toml").exists()

    plan.copytree(HERE / "core", ".harness/core")
    plan.copytree(HERE / "bindings", ".harness/bindings")
    plan.write(".harness/harness.py", read(HERE / "harness.py"))
    plan.write(".harness/VERSION", VERSION + "\n")
    plan.write(".harness/project.toml", prof.to_toml(), overwrite=False)

    for d in AI_DIRS:
        plan.mkdir(f".ai/{d}")
    catalog = plan.root / ".ai/knowledge/failures.md"
    seed = read(HERE / "presets" / prof.stack / "failures.md")
    existing = read(catalog) or "# Failure catalog\n\nSchema: `.harness/core/schemas/failure-entry.md`.\n"
    have = set(re.findall(r"^## (F-\w+)", existing, re.M))
    new_entries = [
        e
        for e in re.split(r"(?m)^(?=## F-)", seed)
        if e.startswith("## F-") and re.match(r"## (F-\w+)", e).group(1) not in have
    ]
    plan.write(
        ".ai/knowledge/failures.md", existing.rstrip() + "\n\n" + "\n".join(new_entries) if new_entries else existing
    )
    plan.write(".ai/loop/state.json", json.dumps(new_state(), indent=2) + "\n", overwrite=False)

    agents_path = root / "AGENTS.md"
    agents = read(agents_path) or (
        f"# AGENTS.md\n\nWorking agreement for AI agents on `{root.name}`.\n\n"
        "## Project\n\n(fill in: purpose, stack, commands, invariants)\n"
    )
    plan.write("AGENTS.md", upsert_block(agents))
    if not (root / "CLAUDE.md").exists():
        plan.write("CLAUDE.md", "@AGENTS.md\n")

    gi = read(root / ".gitignore")
    if not re.search(AI_IGNORE, gi):
        plan.write(".gitignore", gi.rstrip() + ("\n" if gi else "") + "\n# local agent workspace\n.ai/\n")
    render_vendor(plan, load_bindings(root))

    if fresh_profile:
        plan.notes += [f"project.toml: {n}" for n in prof.notes]
    if migrate:
        report = [
            "# reins 마이그레이션 리포트",
            "",
            f"- 시각: {now():%Y-%m-%d %H:%M}",
            f"- 템플릿: v{VERSION}",
            f"- 감지된 스택: {prof.stack} ({prof.package_manager or '-'})",
            "",
            "| 기존 | 내용 | 처리 |",
            "|---|---|---|",
            *legacy,
            "",
            "## 감지된 게이트",
            "",
            "```toml",
            prof.to_toml().strip(),
            "```",
            "",
        ]
        if plan.notes:
            report += ["## 확인 필요", "", *[f"- {n}" for n in plan.notes], ""]
        plan.write(f".ai/migration/{stamp()}_harness.md", "\n".join(report))
    changed = sum(1 for k, _ in plan.actions if k in ("create", "update"))
    if changed:
        plan.write(
            f".ai/history/{stamp()}_harness-{'migrate' if migrate else 'install'}.md",
            f"decisions: reins, harness-{'migrate' if migrate else 'install'}\n\n"
            f"# reins v{VERSION} {'migrate' if migrate else 'install'}\n\n"
            f"- 스택: {prof.stack}; 게이트: {', '.join(prof.gates) or '없음 — project.toml 채우기'}\n"
            f"- 변경 파일: {changed}\n",
        )

    print(f"{'[dry-run] ' if a.dry_run else ''}{'migrate' if migrate else 'install'} → {root}")
    print(f"stack: {prof.stack} ({prof.package_manager or '-'}); gates: {', '.join(prof.gates) or 'none'}")
    if prof.subprojects:
        print("other stacks: " + "; ".join(prof.subprojects))
    print(plan.summary())
    for n in plan.notes:
        print(f"note: {n}")
    if migrate and a.dry_run:
        print("\nlegacy:")
        for r in legacy:
            print("  " + r)
    return 0


def cmd_render(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    plan = Plan(root, a.dry_run)
    agents = read(root / "AGENTS.md")
    if agents:
        plan.write("AGENTS.md", upsert_block(agents))
    render_vendor(plan, load_bindings(root))
    print(plan.summary())
    return 0


def load_profile(root: Path) -> dict:
    p = root / ".harness" / "project.toml"
    if not p.exists():
        sys.exit(f"missing {p} — run install first")
    return tomllib.loads(read(p))


def catalog_matches(root: Path, output: str) -> list[str]:
    hits = []
    text = read(root / ".ai" / "knowledge" / "failures.md")
    for m in re.finditer(r"^## (F-\w+)[^\n]*\n- symptom: (.*)$", text, re.M):
        for sym in re.findall(r"`([^`]{6,})`", m.group(2)):
            if sym in output:
                hits.append(m.group(1))
                break
    return hits


def cmd_gate(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    prof = load_profile(root)
    gates: dict[str, str] = prof.get("gates", {})
    cmds: dict[str, str] = prof.get("commands", {})
    names = list(gates) if a.name == "all" else [a.name]
    worst = 0
    for name in names:
        cmd = gates.get(name) or cmds.get(name)
        if not cmd:
            print(f"{name:<10} SKIP  (no command in .harness/project.toml)")
            continue
        t0 = now()
        proc = subprocess.run(cmd, shell=True, cwd=root, capture_output=a.summary, text=True)
        secs = (now() - t0).total_seconds()
        ok = proc.returncode == 0
        print(f"{name:<10} {'ok  ' if ok else 'FAIL'}  {secs:6.1f}s  {cmd}")
        if not ok:
            worst = proc.returncode or 1
            if a.summary:
                out = (proc.stdout or "") + (proc.stderr or "")
                tail = out.strip().splitlines()[-a.tail :]
                print("\n".join("    " + line for line in tail))
                hits = catalog_matches(root, out)
                if hits:
                    print(f"    catalog: {', '.join(hits)}")
            if a.fail_fast:
                break
    return worst


def new_state() -> dict:
    return {
        "schema": 1,
        "line": None,
        "target": None,
        "item": None,
        "stage": "idle",
        "rounds": {"verify": 0, "review": 0, "qa": 0, "escalate": 0},
        "last_report": None,
        "blocked_on": None,
        "updated": now().isoformat(timespec="seconds"),
    }


def state_path(root: Path) -> Path:
    return root / ".ai" / "loop" / "state.json"


def load_state(root: Path) -> dict:
    p = state_path(root)
    return json.loads(read(p)) if p.exists() else new_state()


def save_state(root: Path, st: dict) -> None:
    st["updated"] = now().isoformat(timespec="seconds")
    p = state_path(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(st, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def cmd_state(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    st = load_state(root)
    if a.action == "reset":
        st = new_state()
        save_state(root, st)
    elif a.action == "set":
        for key in ("line", "target", "item", "stage", "blocked_on"):
            val = getattr(a, key)
            if val is not None:
                if key == "stage" and val not in STAGES:
                    sys.exit(f"unknown stage {val}; one of {', '.join(STAGES)}")
                st[key] = None if val == "-" else val
        save_state(root, st)
    print(json.dumps(st, indent=2, ensure_ascii=False))
    return 0


def transition(st: dict, stage: str, result: str, stop: str) -> tuple[str, str]:
    """Return (next stage, reason). Mutates round counters."""
    r = st.setdefault("rounds", {})
    if stop in ("knowledge", "intent"):
        return "human", f"{stop} stop"
    if stage in ("verify", "review", "qa") and result == "pass":
        r[stage] = 0
        return {"verify": "review", "review": "qa", "qa": "write"}[stage], "passed"
    if stage in ("verify", "review", "qa"):
        r[stage] = r.get(stage, 0) + 1
        if r[stage] > LIMITS[stage]:
            r["escalate"] = r.get("escalate", 0) + 1
            return "escalate", f"{stage} failed {r[stage]} rounds (limit {LIMITS[stage]})"
        return ("triage" if stage == "qa" else "work"), f"{stage} round {r[stage]}"
    if stage == "escalate":
        if result in ("pass", "done"):
            r.update(verify=0, review=0, qa=0, escalate=0)
            return "work", "escalation produced a fix plan; round budgets reset"
        r["escalate"] = r.get("escalate", 0) + 1
        return ("escalate", "next escalation level") if r["escalate"] <= 2 else ("human", "escalation exhausted")
    flow = {
        "analyze": "design",
        "design": "work",
        "work": "verify",
        "triage": "work",
        "write": "release",
        "release": "idle",
    }
    if result in ("fail", "blocked"):
        return "human", f"{stage} {result}"
    return flow.get(stage, "idle"), "done"


def cmd_advance(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    st = load_state(root)
    meta, _ = frontmatter(read(Path(a.handoff)))
    stage, result, stop = meta.get("stage", st["stage"]), meta.get("result", "done"), meta.get("stop", "none")
    nxt, why = transition(st, stage, result, stop)
    st["stage"], st["last_report"] = nxt, str(Path(a.handoff))
    if meta.get("decision"):
        st["blocked_on"] = meta["decision"]
    save_state(root, st)
    rec = {
        "ts": now().isoformat(timespec="seconds"),
        "stage": stage,
        "result": result,
        "round": st["rounds"].get(stage, 0),
        "model": meta.get("model", ""),
        "asked_human": nxt == "human",
        "stop_kind": stop,
    }
    with (root / ".ai" / "loop" / "metrics.jsonl").open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"{stage}:{result} → {nxt} ({why})")
    return 0


def build_prompt(root: Path, stage: str, st: dict) -> str:
    role = ROLE_OF.get(stage, stage)
    role_file = f".harness/core/roles/{'triage' if role == 'orchestrator' else role}.md"
    extra = (
        (
            "\nYou are the escalation step: find the root cause the earlier rounds missed, using "
            f"the reports in .ai/handoff/. Last report: {st.get('last_report')}.\n"
        )
        if stage == "escalate"
        else ""
    )
    return (
        f"You are the '{stage}' stage of the agent loop in this repository.\n"
        f"Read AGENTS.md, .harness/core/loop.md, and {role_file}; follow them.\n"
        f"Loop state: {json.dumps(st, ensure_ascii=False)}\n{extra}"
        f"Do only this stage. Finish by writing one handoff in .ai/handoff/ "
        f"(.harness/core/schemas/handoff.md) and running "
        f"`python3 .harness/harness.py advance <handoff>`.\n"
    )


def cmd_next(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    st = load_state(root)
    stage = st["stage"]
    role, b = binding_for(load_bindings(root), stage, st)
    print(f"stage:   {stage}")
    if stage in ("idle", "human", "release"):
        why = {
            "idle": "nothing scheduled — `state set --target … --stage …`",
            "human": f"waiting for a person: {st.get('blocked_on') or st.get('last_report')}",
            "release": "user-invoked: run the project's release procedure yourself",
        }[stage]
        print(f"action:  {why}")
        return 0
    print(f"role:    {role} → .harness/core/roles/{'triage' if role in ('orchestrator', 'escalate') else role}.md")
    print(f"binding: {b.get('agent', '?')} / {b.get('model', '?')}")
    print(f"run:     python3 .harness/harness.py dispatch {stage}   (or in-session: /step {stage})")
    return 0


def cmd_prompt(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    print(build_prompt(root, a.stage, load_state(root)))
    return 0


def cmd_dispatch(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    st = load_state(root)
    bind = load_bindings(root)
    role, b = binding_for(bind, a.stage, st)
    agent = bind["agents"].get(b.get("agent", ""), {})
    if not agent:
        sys.exit(f"no agent bound for role {role}")
    prompt = build_prompt(root, a.stage, st)
    pf = root / ".ai" / "loop" / f"prompt_{a.stage}.md"
    pf.parent.mkdir(parents=True, exist_ok=True)
    pf.write_text(prompt, encoding="utf-8")
    cmd = [
        part.replace("{model}", b.get("model", "")).replace("{prompt}", prompt).replace("{prompt_file}", str(pf))
        for part in agent["cmd"]
    ]
    shown = [c if c != prompt else f"<prompt: {pf.relative_to(root)}>" for c in cmd]
    print(f"{role} → {' '.join(shown)}")
    if a.dry_run:
        return 0
    if not shutil.which(cmd[0]):
        sys.exit(f"{cmd[0]} not on PATH")
    return subprocess.run(cmd, cwd=root).returncode


def cmd_doctor(a: argparse.Namespace) -> int:
    root = project_root(a.project)
    issues, oks = [], []

    def check(cond: bool, ok: str, bad: str) -> None:
        (oks if cond else issues).append(ok if cond else bad)

    inst = read(root / ".harness" / "VERSION").strip()
    check(bool(inst), f"installed v{inst}", "not installed (.harness/VERSION missing)")
    if inst and inst != VERSION:
        issues.append(f"installed v{inst}, this harness.py is v{VERSION} — run update")
    check(BEGIN in read(root / "AGENTS.md"), "AGENTS.md managed block", "AGENTS.md has no managed block")
    check(
        "@AGENTS.md" in read(root / "CLAUDE.md"),
        "CLAUDE.md imports AGENTS.md",
        "CLAUDE.md missing or does not import @AGENTS.md",
    )
    check(bool(re.search(AI_IGNORE, read(root / ".gitignore"))), ".ai/ gitignored", ".ai/ is not in .gitignore")
    if (root / ".harness" / "project.toml").exists():
        prof = load_profile(root)
        for k, v in prof.get("gates", {}).items():
            exe = v.split()[0] if v else ""
            check(
                bool(v) and (exe in ("test", "./gradlew") or shutil.which(exe) is not None),
                f"gate {k}: {v}",
                f"gate {k}: `{exe}` not found on PATH",
            )
        check(bool(prof.get("gates")), "gates defined", "no gates in project.toml")
    bind = load_bindings(root)
    used = {r.get("agent") for r in bind["roles"].values()}
    for name in sorted(x for x in used if x):
        exe = bind["agents"].get(name, {}).get("cmd", ["?"])[0]
        check(shutil.which(exe) is not None, f"agent {name}: {exe}", f"agent {name}: `{exe}` not on PATH")
    for line in oks:
        print(f"ok    {line}")
    for line in issues:
        print(f"issue {line}")
    return 1 if issues else 0


