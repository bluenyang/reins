# --------------------------------------------------------------------------- helpers


def now() -> dt.datetime:
    return dt.datetime.now().astimezone()


def stamp() -> str:
    return now().strftime("%Y-%m-%d-%H%M")


def template_root() -> Path:
    """The directory holding core/, presets/, bindings/ — template repo or <project>/.harness."""
    return HERE


def project_root(arg: str | None) -> Path:
    if arg:
        return Path(arg).resolve()
    if HERE.name == ".harness":
        return HERE.parent
    return Path.cwd().resolve()


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8") if p.exists() else ""


def frontmatter(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    meta: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.split("#", 1)[0].strip().strip("'\"")
    return meta, m.group(2)


def toml_value(v: object) -> str:
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return json.dumps(str(v), ensure_ascii=False)


# --------------------------------------------------------------------------- plan of changes


@dataclass
class Plan:
    root: Path
    dry: bool
    actions: list[tuple[str, str]] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def write(self, rel: str, content: str, *, overwrite: bool = True) -> None:
        p = self.root / rel
        old = read(p)
        if p.exists() and not overwrite:
            self.actions.append(("keep", rel))
            return
        if old == content:
            self.actions.append(("same", rel))
            return
        self.actions.append(("update" if p.exists() else "create", rel))
        if not self.dry:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")

    def mkdir(self, rel: str) -> None:
        p = self.root / rel
        if p.is_dir():
            return
        self.actions.append(("mkdir", rel))
        if not self.dry:
            p.mkdir(parents=True, exist_ok=True)

    def copytree(self, src: Path, rel: str) -> None:
        for f in sorted(src.rglob("*")):
            if f.is_file() and "__pycache__" not in f.parts:
                self.write(f"{rel}/{f.relative_to(src).as_posix()}", f.read_text(encoding="utf-8"))

    def summary(self) -> str:
        counts: dict[str, int] = {}
        for kind, _ in self.actions:
            counts[kind] = counts.get(kind, 0) + 1
        lines = [f"  {k:<7} {r}" for k, r in self.actions if k not in ("same",)]
        head = ", ".join(f"{k} {n}" for k, n in sorted(counts.items()))
        return "\n".join([f"changes: {head or 'none'}", *lines])


