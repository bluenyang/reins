@dataclass
class Profile:
    name: str
    stack: str
    package_manager: str = ""
    gates: dict[str, str] = field(default_factory=dict)
    commands: dict[str, str] = field(default_factory=dict)
    source: list[str] = field(default_factory=list)
    docs: list[str] = field(default_factory=list)
    subprojects: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def to_toml(self) -> str:
        out = [
            "# Project profile for reins. Committed; shared by every agent and person.",
            "# `gate all` runs [gates] in order. Edit freely — `harness.py update` keeps this file.",
            "schema = 1",
            f"name = {toml_value(self.name)}",
            f"stack = {toml_value(self.stack)}",
            f"package_manager = {toml_value(self.package_manager)}",
            "",
            "[gates]",
        ]
        out += [f"{k} = {toml_value(v)}" for k, v in self.gates.items()]
        out += ["", "[commands]   # used by roles, not part of `gate all`"]
        out += [f"{k} = {toml_value(v)}" for k, v in self.commands.items()]
        out += [
            "",
            "[paths]",
            f"source = {toml_value(self.source)}   # qa must not read these",
            f"docs = {toml_value(self.docs)}",
        ]
        if self.subprojects:
            out += ["", "# Other stacks found below the root — add their gates above if they matter:"]
            out += [f"#   {s}" for s in self.subprojects]
        return "\n".join(out) + "\n"


def detect(root: Path, forced: str | None) -> Profile:
    prof = Profile(name=root.name, stack="unknown")
    found = {
        "node": (root / "package.json").exists(),
        "go": (root / "go.mod").exists(),
        "gradle-kotlin": (root / "build.gradle.kts").exists() or (root / "settings.gradle.kts").exists(),
    }
    stack = forced or next((s for s, ok in found.items() if ok), "unknown")
    prof.stack = stack
    if stack == "node":
        _node(root, prof)
    elif stack == "go":
        _go(root, prof)
    elif stack == "gradle-kotlin":
        _gradle(root, prof)
    prof.source = [
        d
        for d in (
            "src",
            "apps",
            "packages",
            "internal",
            "cmd",
            "pkg",
            "lib",
            "server",
            "dashboard",
            "web",
            "frontend",
            "backend",
        )
        if (root / d).is_dir()
    ]
    prof.docs = [d for d in ("README.md", "README.ko.md", "CONTRIBUTING.md", "docs") if (root / d).exists()]
    for marker, label in (("package.json", "node"), ("go.mod", "go"), ("build.gradle.kts", "gradle-kotlin")):
        for p in sorted(root.glob(f"*/{marker}")) + sorted(root.glob(f"*/*/{marker}")):
            if "node_modules" in p.parts:
                continue
            rel = p.parent.relative_to(root).as_posix()
            if label != stack or not (root / "pnpm-workspace.yaml").exists():
                prof.subprojects.append(f"{label}: {rel}")
    if stack == "node" and found["go"]:
        prof.subprojects.append("go: .")
    prof.subprojects = prof.subprojects[:12]
    return prof


def _node(root: Path, prof: Profile) -> None:
    pm = (
        "pnpm"
        if (root / "pnpm-lock.yaml").exists()
        else "yarn"
        if (root / "yarn.lock").exists()
        else "bun"
        if (root / "bun.lockb").exists() or (root / "bun.lock").exists()
        else "npm"
    )
    prof.package_manager = pm
    try:
        scripts: dict[str, str] = json.loads(read(root / "package.json")).get("scripts", {})
    except json.JSONDecodeError:
        scripts = {}

    def pick(*names: str) -> str:
        for n in names:
            if n in scripts:
                return f"{pm} run {n}"
        return ""

    def mutating(name: str) -> bool:
        body = scripts.get(name, "")
        return bool(re.search(r"--fix\b|--write\b|\s-w\b|eslint\s+--fix", body))

    lint_name = next((n for n in ("lint:check", "lint") if n in scripts and not mutating(n)), "")
    gates = {
        "format": pick("format:check", "fmt:check", "format-check", "prettier:check"),
        "lint": pick(lint_name) if lint_name else "",
        "typecheck": pick("typecheck", "type-check", "check-types", "tsc"),
        "test": pick("test", "test:unit"),
        "build": pick("build"),
    }
    for name in sorted(scripts):
        if name.startswith("check:") and not mutating(name):
            gates[name.replace(":", "_")] = pick(name)
    prof.gates = {k: v for k, v in gates.items() if v}
    if not gates["format"] and "format" in scripts:
        prof.notes.append("no non-mutating format check script (only `format`, which writes) — add `format:check`")
    if not gates["lint"] and "lint" in scripts:
        prof.notes.append("`lint` script rewrites files (--fix) and no `lint:check` exists — add one for the gate")
    if not gates["test"]:
        prof.notes.append("no `test` script — verify has no test gate; QA scenarios carry all behaviour checks")
    prof.commands = {
        "install": f"{pm} install --frozen-lockfile"
        if pm == "pnpm"
        else "yarn install --immutable"
        if pm == "yarn"
        else f"{pm} ci"
        if pm == "npm"
        else f"{pm} install",
        "check": pick("check", "verify", "ci"),
        "format_fix": pick("format", "fmt"),
        "lint_fix": pick("lint:fix"),
        "dev": pick("dev", "start:dev", "start"),
        "e2e": pick("e2e", "test:e2e"),
    }


def _go(root: Path, prof: Profile) -> None:
    prof.package_manager = "go"
    lint = "golangci-lint run" if any(root.glob(".golangci.*")) else ""
    prof.gates = {
        k: v
        for k, v in {
            "format": 'test -z "$(gofmt -l .)" || (gofmt -l .; exit 1)',
            "vet": "go vet ./...",
            "lint": lint,
            "test": "go test ./...",
            "build": "go build ./...",
        }.items()
        if v
    }
    prof.commands = {"format_fix": "gofmt -w .", "race": "go test -race ./...", "dev": "go run .", "e2e": ""}


def _gradle(root: Path, prof: Profile) -> None:
    gw = "./gradlew" if (root / "gradlew").exists() else "gradle"
    prof.package_manager = "gradle"
    build_text = read(root / "build.gradle.kts") + "".join(read(p) for p in root.glob("*/build.gradle.kts"))
    lint = (
        f"{gw} ktlintCheck"
        if "ktlint" in build_text
        else f"{gw} spotlessCheck"
        if "spotless" in build_text
        else f"{gw} detekt"
        if "detekt" in build_text
        else ""
    )
    prof.gates = {k: v for k, v in {"lint": lint, "test": f"{gw} test", "build": f"{gw} build -x test"}.items() if v}
    prof.commands = {
        "format_fix": lint.replace("Check", "Format").replace("spotlessFormat", "spotlessApply") if lint else "",
        "dev": f"{gw} bootRun" if "spring" in build_text.lower() else "",
        "e2e": "",
    }


