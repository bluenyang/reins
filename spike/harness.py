def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="harness.py", description=__doc__.split("\n")[0])
    p.add_argument("--version", action="version", version=VERSION)
    sub = p.add_subparsers(dest="cmd", required=True)

    for name, help_ in (
        ("install", "install or update the harness in a project (from the template repo)"),
        ("update", "same as install; keeps project.toml and your files"),
        ("migrate", "install + report on existing harness files (.ai/migration/)"),
    ):
        s = sub.add_parser(name, help=help_)
        s.add_argument("project")
        s.add_argument("--stack", choices=["node", "go", "gradle-kotlin"])
        s.add_argument("--dry-run", action="store_true")

    s = sub.add_parser("render", help="regenerate AGENTS.md block and vendor files")
    s.add_argument("--project")
    s.add_argument("--dry-run", action="store_true")

    s = sub.add_parser("gate", help="run gates from .harness/project.toml")
    s.add_argument("name", nargs="?", default="all")
    s.add_argument("--summary", action="store_true", help="capture output, print failing tails only")
    s.add_argument("--tail", type=int, default=30)
    s.add_argument("--fail-fast", action="store_true")
    s.add_argument("--project")

    s = sub.add_parser("state", help="show or change .ai/loop/state.json")
    s.add_argument("action", choices=["show", "set", "reset"], nargs="?", default="show")
    for k in ("line", "target", "item", "stage", "blocked-on"):
        s.add_argument(f"--{k}", dest=k.replace("-", "_"))
    s.add_argument("--project")

    s = sub.add_parser("next", help="print the next stage, role, and binding")
    s.add_argument("--project")

    s = sub.add_parser("advance", help="apply a handoff report to the loop state")
    s.add_argument("handoff")
    s.add_argument("--project")

    s = sub.add_parser("prompt", help="print the prompt for a stage")
    s.add_argument("stage", choices=[x for x in STAGES if x not in ("idle", "human")])
    s.add_argument("--project")

    s = sub.add_parser("dispatch", help="run a stage on its bound agent CLI")
    s.add_argument("stage", choices=[x for x in STAGES if x not in ("idle", "human")])
    s.add_argument("--dry-run", action="store_true")
    s.add_argument("--project")

    s = sub.add_parser("doctor", help="check the installation, gates, and agent CLIs")
    s.add_argument("--project")

    a = p.parse_args(argv)
    handlers = {
        "install": cmd_install,
        "update": cmd_install,
        "migrate": lambda x: cmd_install(x, migrate=True),
        "render": cmd_render,
        "gate": cmd_gate,
        "state": cmd_state,
        "next": cmd_next,
        "advance": cmd_advance,
        "prompt": cmd_prompt,
        "dispatch": cmd_dispatch,
        "doctor": cmd_doctor,
    }
    return handlers[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
